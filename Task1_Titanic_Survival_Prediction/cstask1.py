#!/usr/bin/env python3
"""
Titanic survival prediction
===========================
Combines two sources of information, both treated as important:

  A) DATASET features  - real columns from the Kaggle file
                         (Pclass, Sex, Age, SibSp, Parch, Fare, Cabin deck, Embarked, Title ...)
  B) SCENARIO features - your 6 extra points about the sinking:
        1. distance to the lifeboat
        2. is the path to the boat clear
        3. is the person's age suited to reacting quickly
        4. has an emergency life jacket
        5. how much rush / crowding there is at the boats
        6. how many fit people (by age range) are able to help others

IMPORTANT - about points 1, 2, 4, 5:
The Kaggle file has NO columns for them. They are therefore built as *simulated
scenario features* from real passenger info (deck, class, family size, age) plus
random noise. They are NEVER computed from the Survived column, so there is no
label leakage. Points 3 and 6 are derived from the real Age / Ticket columns.
Because the simulated points are derived from the same columns, they cannot add
brand-new real-world information; the script reports Dataset-only vs
Scenario-only vs Combined so you can see exactly what they contribute.

Usage:
    python titanic_survival.py                    # downloads data with kagglehub
    python titanic_survival.py --csv Titanic-Dataset.csv
"""
