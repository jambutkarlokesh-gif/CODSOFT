def find_local_csv():
    # __file__ does not exist inside a Colab / Jupyter cell -> fall back to the working folder
    here = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() else os.getcwd()
    for folder in (here, os.path.join(here, "data"), os.getcwd(), os.path.join(os.getcwd(), "data")):
        for name in ("IMDb_Movies_India.csv", "IMDb Movies India.csv", "IMDb_Movies_India[2].csv"):
            p = os.path.join(folder, name)
            if os.path.isfile(p):
                return p
    return None


def load_data(csv_path=None):
    csv_path = csv_path or find_local_csv()
    if csv_path is None:
        sys.exit("Could not find IMDb_Movies_India.csv. Put it next to this script "
                 "(or in a 'data' folder) or run:  python movie_rating_prediction.py --csv <path>")
    df = None
    for enc in ("utf-8", "latin-1"):  # this dataset is Latin-1, not UTF-8
        try:
            df = pd.read_csv(csv_path, encoding=enc)
            break
        except UnicodeDecodeError:
            continue
    need = set(RAW_COLS + ["Name", "Rating"])
    if df is None or need - set(df.columns):
        sys.exit(f"Unexpected file format. Needed columns: {sorted(need)}")
    n_raw = len(df)
    df = df.drop_duplicates()
    df = df.dropna(subset=["Rating"]).reset_index(drop=True)
    log(f"Loaded {n_raw} rows from {csv_path}")
    log(f"Kept {len(df)} movies that have a rating (rows without a rating cannot be used).")
    return df


