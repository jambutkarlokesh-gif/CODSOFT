# 5. Models + evaluation
# --------------------------------------------------------------------------- #
FEATURE_SETS = {
    "A) Genre + director + actors (+ year, duration)": False,
    "B) A + number of votes": True,
}
GROUPS = {"Genre": ["Genre"], "Director": ["Director"], "Actors": ACTOR_COLS,
          "Year": ["Year"], "Duration": ["Duration"], "Votes": ["Votes"]}


def make_models():
    return {
        "Baseline (always predicts the mean)": DummyRegressor(),
        "Ridge": Pipeline([("sc", StandardScaler()), ("m", Ridge(alpha=10.0))]),
        "Random Forest": RandomForestRegressor(n_estimators=300, min_samples_leaf=3,
                                               n_jobs=-1, random_state=SEED),
        "Gradient Boosting": GradientBoostingRegressor(n_estimators=300, learning_rate=0.05,
                                                        max_depth=3, subsample=0.8,
                                                        random_state=SEED),
    }


def make_pipeline(model, use_votes):
    return Pipeline([("feat", MovieFeatures(use_votes=use_votes)), ("model", model)])


def rmse(y, p):
    return float(np.sqrt(mean_squared_error(y, p)))


def cross_validate_all(X, y):
    cv = KFold(5, shuffle=True, random_state=SEED)
    scoring = {"rmse": "neg_root_mean_squared_error", "mae": "neg_mean_absolute_error", "r2": "r2"}
    rows = []
    for fs, use_votes in FEATURE_SETS.items():
        for name, model in make_models().items():
            res = cross_validate(make_pipeline(model, use_votes), X, y, cv=cv, scoring=scoring)
            rows.append({"feature_set": fs, "model": name,
                         "rmse": -res["test_rmse"].mean(), "mae": -res["test_mae"].mean(),
                         "r2": res["test_r2"].mean(), "rmse_std": res["test_rmse"].std()})
    return pd.DataFrame(rows).round(4)


def group_importance(pipe, X_test, y_test, groups, n_repeats=5, seed=SEED):
    """Increase in test RMSE when a group of input columns is shuffled (bigger = more important)."""
    rng = np.random.default_rng(seed)
    base = rmse(y_test, pipe.predict(X_test))
    out = {}
    for name, cols in groups.items():
        deltas = []
        for _ in range(n_repeats):
            Xp = X_test.copy()
            idx = rng.permutation(len(Xp))
            Xp[cols] = X_test[cols].iloc[idx].to_numpy()
            deltas.append(rmse(y_test, pipe.predict(Xp)) - base)
        out[name] = float(np.mean(deltas))
    return out


def holdout_and_plots(df, results, out):
    X, y = df[RAW_COLS], df["Rating"].to_numpy()
    idx_tr, idx_te = train_test_split(np.arange(len(df)), test_size=0.2, random_state=SEED)
    X_tr, X_te, y_tr, y_te = X.iloc[idx_tr], X.iloc[idx_te], y[idx_tr], y[idx_te]
    log(f"\n=== Hold-out test: train on {len(idx_tr)} movies, test on {len(idx_te)} unseen movies ===")

    fitted, importances, rows = {}, {}, []
    for fs, use_votes in FEATURE_SETS.items():
        sub = results[(results["feature_set"] == fs) & (~results["model"].str.startswith("Baseline"))]
        best = sub.sort_values("rmse").iloc[0]["model"]
        pipe = make_pipeline(make_models()[best], use_votes).fit(X_tr, y_tr)
        pred = np.clip(pipe.predict(X_te), 1, 10)
        base_pred = np.full(len(y_te), y_tr.mean())
        err = np.abs(pred - y_te)
        rows.append({"feature_set": fs, "best_model": best,
                     "rmse": rmse(y_te, pred), "mae": mean_absolute_error(y_te, pred),
                     "r2": r2_score(y_te, pred), "baseline_rmse": rmse(y_te, base_pred),
                     "within_0.5": 100 * (err <= 0.5).mean(), "within_1.0": 100 * (err <= 1.0).mean()})
        fitted[fs] = (pipe, pred)
        grp = {k: v for k, v in GROUPS.items() if use_votes or k != "Votes"}
        importances[fs] = group_importance(pipe, X_te, y_te, grp)
    hold = pd.DataFrame(rows).round(3)
    hold.to_csv(os.path.join(out, "holdout_results.csv"), index=False)
    for _, r in hold.iterrows():
        log(f"\n{r['feature_set']}  ->  best model: {r['best_model']}")
        log(f"  RMSE {r['rmse']:.3f} (baseline {r['baseline_rmse']:.3f})   MAE {r['mae']:.3f}   "
            f"R2 {r['r2']:.3f}")
        log(f"  Predictions within 0.5 rating points: {r['within_0.5']:.0f}%   "
            f"within 1.0 point: {r['within_1.0']:.0f}%")

    # sample predictions (feature set A = what the brief asks for)
    fsA = list(FEATURE_SETS)[0]
    sample = pd.DataFrame({"movie": df["Name"].iloc[idx_te].to_numpy(),
                           "year": df["Year"].astype(str).str.extract(r"(\d{4})")[0].iloc[idx_te].to_numpy(),
                           "actual": y_te, "predicted_A": fitted[fsA][1].round(2),
                           "predicted_B": fitted[list(FEATURE_SETS)[1]][1].round(2)})
    sample.to_csv(os.path.join(out, "test_predictions.csv"), index=False)
    log("\nExample predictions on unseen movies (A = genre/director/actors only):")
    log(sample.head(8).to_string(index=False))

    log("\nWhat drives the prediction (rise in test RMSE when that input is shuffled):")
    imp = pd.DataFrame(importances).round(3)
    imp.columns = ["A", "B"]
    log(imp.to_string())
    imp.to_csv(os.path.join(out, "factor_importance.csv"))

    # --- charts ---
    style()
    fig, axes = plt.subplots(1, 2, figsize=(9.5, 4.4), sharex=True, sharey=True)
    for ax, (fs, (pipe, pred)), title in zip(axes, fitted.items(),
                                             ["A) Genre, director, actors", "B) A + votes"]):
        ax.scatter(y_te, pred, s=14, color=BLUE, alpha=0.45, edgecolor="none")
        ax.plot([1, 10], [1, 10], color=INK2, linestyle="--", linewidth=1)
        ax.set_title(title)
        ax.set_xlabel("Actual rating")
        r2 = hold.loc[hold["feature_set"] == fs, "r2"].iloc[0]
        ax.text(0.04, 0.94, f"R2 = {r2:.2f}", transform=ax.transAxes, va="top", color=INK2)
    axes[0].set_ylabel("Predicted rating")
    save(fig, out, "predicted_vs_actual.png")

    names = list(GROUPS)
    order = sorted(names, key=lambda k: -max(importances[fs].get(k, 0) for fs in importances))
    order = order[::-1]
    fig, ax = plt.subplots(figsize=(7, 4))
    h = 0.36
    pos = np.arange(len(order))
    labels = list(FEATURE_SETS)
    ax.barh(pos + h / 2, [importances[labels[0]].get(k, np.nan) for k in order], height=h,
            color=BLUE, label="A) Genre, director, actors")
    ax.barh(pos - h / 2, [importances[labels[1]].get(k, np.nan) for k in order], height=h,
            color=ORANGE, label="B) A + votes")
    ax.set_yticks(pos)
    ax.set_yticklabels(order)
    ax.set_xlabel("Increase in test RMSE when shuffled (higher = matters more)")
    ax.set_title("What influences the predicted rating")
    ax.grid(axis="y", visible=False)
    ax.legend(frameon=False, loc="lower right")
    save(fig, out, "importance_by_factor.png")


