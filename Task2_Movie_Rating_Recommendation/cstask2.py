def explore(df, out):
    d = MovieFeatures._prepare(df[RAW_COLS])
    d["Rating"] = df["Rating"].to_numpy()
    r = d["Rating"]
    log("\n=== Data overview ===")
    log(f"Rating: mean {r.mean():.2f}, median {r.median():.2f}, std {r.std():.2f}, "
        f"range {r.min():.1f}-{r.max():.1f}")
    log("Missing values among rated movies: " + ", ".join(
        f"{c} {int(n)}" for c, n in {
            "Year": d["year"].isna().sum(), "Duration": d["duration"].isna().sum(),
            "Genre": (d["genres"].map(len) == 0).sum(), "Director": d["director"].isna().sum(),
            "Actor 1": d["Actor 1"].isna().sum()}.items()))
    log("Spearman correlation with rating: " + ", ".join(
        f"{c} {d[c].corr(r, method='spearman'):+.2f}" for c in ("year", "duration", "votes")))

    # genres
    ex = d[["genres", "Rating"]].explode("genres").dropna(subset=["genres"])
    g = ex.groupby("genres")["Rating"].agg(["mean", "count"])
    g = g[g["count"] >= 100].sort_values("mean", ascending=False)
    log("\nAverage rating by genre (genres with >=100 movies):")
    log(g.round(2).head(6).to_string())
    log("   ...")
    log(g.round(2).tail(4).to_string())
    g.to_csv(os.path.join(out, "genre_summary.csv"))

    # decades
    d["decade"] = (d["year"] // 10 * 10)
    dec = d.groupby("decade")["Rating"].agg(["mean", "count"])
    dec = dec[dec["count"] >= 30]
    log("\nAverage rating by decade:")
    log(dec.round(2).to_string())

    # directors / actors
    dr = d.groupby("director")["Rating"].agg(["mean", "count"])
    dr = dr[dr["count"] >= 5].sort_values("mean", ascending=False)
    log("\nTop directors by average rating (>=5 rated movies):")
    log(dr.round(2).head(8).to_string())
    stacked = pd.concat([pd.DataFrame({"actor": d[c], "Rating": d["Rating"]}) for c in ACTOR_COLS])
    ac = stacked.dropna().groupby("actor")["Rating"].agg(["mean", "count"])
    ac = ac[ac["count"] >= 8].sort_values("mean", ascending=False)
    log("\nTop actors by average rating (>=8 rated movies):")
    log(ac.round(2).head(8).to_string())
    dr.to_csv(os.path.join(out, "director_summary.csv"))
    ac.to_csv(os.path.join(out, "actor_summary.csv"))

    # --- charts ---
    style()
    fig, ax = plt.subplots(figsize=(6.5, 3.6))
    ax.hist(r, bins=np.arange(1, 10.6, 0.5), color=BLUE, edgecolor=SURFACE, linewidth=2)
    ax.set_title("Most movies are rated between 5 and 7")
    ax.set_xlabel("IMDb rating")
    ax.set_ylabel("Number of movies")
    ax.grid(axis="x", visible=False)
    save(fig, out, "rating_distribution.png")

    top = g.head(10).iloc[::-1]
    fig, ax = plt.subplots(figsize=(6.5, 4))
    ax.barh(top.index, top["mean"], color=BLUE, height=0.65)
    for y_, (m, n) in enumerate(zip(top["mean"], top["count"])):
        ax.text(m + 0.03, y_, f"{m:.2f}  (n={int(n)})", va="center", fontsize=8.5, color=INK2)
    ax.set_xlim(0, top["mean"].max() + 1.2)
    ax.set_title("Highest-rated genres (genres with 100+ movies)")
    ax.set_xlabel("Average rating")
    ax.grid(axis="y", visible=False)
    save(fig, out, "avg_rating_by_genre.png")

    fig, ax = plt.subplots(figsize=(6.5, 3.4))
    ax.plot(dec.index.astype(int), dec["mean"], color=BLUE, linewidth=2, marker="o", markersize=7,
            markeredgecolor=SURFACE, markeredgewidth=2)
