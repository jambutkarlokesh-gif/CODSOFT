def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", help="path to IMDb_Movies_India[2].csv")
    ap.add_argument("--out", default=OUT_DIR)
    args, _ = ap.parse_known_args()  # ignores extra arguments Jupyter/Colab passes in
    os.makedirs(args.out, exist_ok=True)

    df = load_data(args.csv)
    explore(df, args.out)

    X, y = df[RAW_COLS], df["Rating"]
    log("\n=== 5-fold cross-validation (lower RMSE / MAE is better, higher R2 is better) ===")
    results = cross_validate_all(X, y)
    results.to_csv(os.path.join(args.out, "cv_results.csv"), index=False)
    log(results.to_string(index=False))

    holdout_and_plots(df, results, args.out)

    with open(os.path.join(args.out, "results_summary.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(_LOG))
    log(f"\nSaved outputs to {os.path.abspath(args.out)}")


if __name__ == "__main__":
    main()