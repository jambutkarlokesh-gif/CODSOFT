#!/usr/bin/env python3
"""
Movie Rating Prediction (IMDb Movies India)
===========================================
Regression model that predicts a movie's rating (1-10) from genre, director,
actors and basic movie info.

Pipeline
--------
1. Load + clean   : handles the Latin-1 encoding, "(2019)" years, "109 min" durations,
                    drops movies that have no rating (nothing to learn from / evaluate).
2. Explore        : rating distribution, genre / decade effects, top directors and actors.
3. Features       : genre multi-hot, director + cast "target encoding" (average rating of
                    their other movies), year, duration.  Target encoding is computed
                    out-of-fold INSIDE every training split, so a movie never sees its own
                    rating (no leakage).
4. Models         : Baseline (mean), Ridge, Random Forest, Gradient Boosting.
5. Evaluate       : 5-fold cross-validation + a final 80/20 hold-out test
                    (RMSE, MAE, R2) for two feature sets:
                      A) Brief features  = genre, director, actors (+ year, duration)
                      B) A + Votes       = adds the number of IMDb votes
                    Votes are shown separately because they are only known AFTER a movie
                    has been released and rated, so B is "easier" than a true forecast.

Usage
-----
    python movie_rating_prediction.py                        # finds the CSV next to the script
    python movie_rating_prediction.py --csv path/to/IMDb_Movies_India.csv
Works as a normal script, and when pasted into a Google Colab / Jupyter cell
(upload IMDb_Movies_India.csv to the working folder first).
"""
