# 2. Feature builder (sklearn transformer, leakage-safe)
# --------------------------------------------------------------------------- #
def _clean_text(s):
    s = s.astype(str).str.strip()
    return s.where(~s.isin(["", "nan", "None", "NaN"]), np.nan)


class MovieFeatures(BaseEstimator, TransformerMixin):
    """Raw movie columns -> numeric feature table.

    Director and cast names are turned into numbers with *smoothed target encoding*:
    the average rating of that person's other movies, pulled toward the global mean when
    the person has few movies.  During fit the encoding of every training movie is computed
    out-of-fold, so a movie's own rating never leaks into its own features.
    """

    def __init__(self, use_votes=False, min_genre_count=30, smoothing=5.0,
                 inner_folds=5, seed=SEED):
        self.use_votes = use_votes
        self.min_genre_count = min_genre_count
        self.smoothing = smoothing
        self.inner_folds = inner_folds
        self.seed = seed

    # ---- parsing: uses no rating information ----
    @staticmethod
    def _prepare(X):
        X = pd.DataFrame(X).reset_index(drop=True)
        d = pd.DataFrame(index=X.index)
        d["year"] = pd.to_numeric(X["Year"].astype(str).str.extract(r"(\d{4})")[0], errors="coerce")
        d["duration"] = pd.to_numeric(X["Duration"].astype(str).str.extract(r"(\d+)")[0], errors="coerce")
        d["votes"] = pd.to_numeric(X["Votes"].astype(str).str.replace(r"[^\d.]", "", regex=True),
                                   errors="coerce")
        genre = _clean_text(X["Genre"]).fillna("")
        d["genres"] = genre.map(lambda g: [x.strip() for x in g.split(",") if x.strip()])
        d["director"] = _clean_text(X["Director"])
        for c in ACTOR_COLS:
            d[c] = _clean_text(X[c])
        return d

    # ---- target encoding tables ----
    @staticmethod
    def _fit_maps(d, y):
        dm = (pd.DataFrame({"k": d["director"].to_numpy(), "y": y}).dropna(subset=["k"])
              .groupby("k")["y"].agg(["sum", "count"]))
        parts = [pd.DataFrame({"k": d[c].to_numpy(), "y": y}) for c in ACTOR_COLS]
        am = pd.concat(parts).dropna(subset=["k"]).groupby("k")["y"].agg(["sum", "count"])
        return dm, am

    def _encode(self, d, maps, gmean):
        dm, am = maps
        m = self.smoothing
        out = pd.DataFrame(index=d.index)
        s = d["director"].map(dm["sum"]).fillna(0)
        c = d["director"].map(dm["count"]).fillna(0)
        out["director_te"] = (s + m * gmean) / (c + m)
        out["director_films"] = np.log1p(c)
        te, cnt = [], []
        for col in ACTOR_COLS:
            s = d[col].map(am["sum"]).fillna(0)
            c = d[col].map(am["count"]).fillna(0)
            te.append((s + m * gmean) / (c + m))
            cnt.append(c)
        te = pd.concat(te, axis=1)
        cnt = pd.concat(cnt, axis=1)
        out["cast_te_mean"] = te.mean(axis=1)
        out["cast_te_max"] = te.max(axis=1)
        out["cast_films_mean"] = np.log1p(cnt.mean(axis=1))
        return out[ENC_COLS]

    def _assemble(self, d, enc):
        f = pd.DataFrame(index=d.index)
        f["year"] = d["year"].fillna(self.year_median_)
        f["year_missing"] = d["year"].isna().astype(int)
        f["duration"] = d["duration"].fillna(self.duration_median_)
        f["duration_missing"] = d["duration"].isna().astype(int)
        f["n_genres"] = d["genres"].map(len)
        for g in self.genres_:
            f["genre_" + g] = d["genres"].map(lambda gs, g=g: int(g in gs))
        if self.use_votes:
            f["log_votes"] = np.log1p(d["votes"].fillna(0))
        out = pd.concat([f, enc.set_axis(d.index)], axis=1)
        self.feature_names_ = list(out.columns)
        return out

    # ---- sklearn API ----
    def fit_transform(self, X, y=None, **fit_params):
        d = self._prepare(X)
        y = np.asarray(y, dtype=float)
        self.global_mean_ = float(y.mean())
        self.year_median_ = float(d["year"].median())
        self.duration_median_ = float(d["duration"].median())
        counts = pd.Series([g for gs in d["genres"] for g in gs]).value_counts()
        self.genres_ = sorted(counts[counts >= self.min_genre_count].index)
        self.maps_ = self._fit_maps(d, y)  # used for new (unseen) movies

        enc = pd.DataFrame(np.zeros((len(d), len(ENC_COLS))), columns=ENC_COLS)
        kf = KFold(self.inner_folds, shuffle=True, random_state=self.seed)
        for tr, te in kf.split(d):  # out-of-fold encoding for the training rows
            maps = self._fit_maps(d.iloc[tr], y[tr])
            enc.iloc[te] = self._encode(d.iloc[te], maps, float(y[tr].mean())).to_numpy()
        return self._assemble(d, enc)

    def fit(self, X, y=None):
        self.fit_transform(X, y)
        return self

    def transform(self, X):
        d = self._prepare(X)
        return self._assemble(d, self._encode(d, self.maps_, self.global_mean_))


