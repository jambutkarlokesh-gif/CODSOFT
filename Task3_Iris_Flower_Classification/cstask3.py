# 6. Main
# --------------------------------------------------------------------------- #
def describe(model, row):
    x = pd.DataFrame([row], columns=FEATURES)
    pred = model.predict(x)[0]
    proba = dict(zip(model.classes_, model.predict_proba(x)[0]))
    conf = ", ".join(f"{k} {v:.0%}" for k, v in sorted(proba.items(), key=lambda kv: -kv[1]))
    return pred, conf


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", help="path to IRIS[1].csv")
    ap.add_argument("--out", default=OUT_DIR)
    ap.add_argument("--predict", nargs=4, type=float,
                    metavar=("SEPAL_LEN", "SEPAL_WID", "PETAL_LEN", "PETAL_WID"),
                    help="classify one new flower (cm)")
    args, _ = ap.parse_known_args()  # ignores extra arguments Jupyter/Colab passes in
    os.makedirs(args.out, exist_ok=True)

    df = load_data(args.csv)
    explore(df, args.out)
    X, y = df[FEATURES], df["species"]

    # hold-out split: untouched until the final evaluation
    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2, stratify=y, random_state=SEED)
    log(f"\nSplit: {len(X_tr)} flowers for training/model selection, {len(X_te)} held back for the final test.")

    log("\n=== Model comparison: 10 x repeated 5-fold CV on the training flowers ===")
    res = compare_models(X_tr, y_tr, args.out)
    log(res.round(4).to_string(index=False))
    best_name = res.iloc[0]["model"]
    gap = res.iloc[0]["accuracy"] - res.iloc[1]["accuracy"]
    log(f"\nBest on average: {best_name}. Its lead over the runner-up is {gap:.1%}, "
        f"compared with a run-to-run spread of about {res.iloc[0]['accuracy_std']:.1%}; "
        "on a dataset this small the top models are practically tied.")
    best = make_models()[best_name]

    # 1) hold-out test
    fitted = clone(best).fit(X_tr, y_tr)
    pred_te = fitted.predict(X_te)
    acc_te = accuracy_score(y_te, pred_te)
    log(f"\n=== Hold-out test ({len(X_te)} unseen flowers) ===")
    log(f"Accuracy: {acc_te:.1%}  ({int((pred_te == y_te).sum())} of {len(y_te)} correct)")
    log(classification_report(y_te, pred_te, digits=3))
    cm_te = confusion_matrix(y_te, pred_te, labels=SPECIES)

    # 2) cross-validated predictions for every flower
    cv_pred = cross_val_predict(clone(best), X, y, cv=StratifiedKFold(5, shuffle=True, random_state=SEED))
    acc_cv = accuracy_score(y, cv_pred)
    log(f"=== 5-fold cross-validated predictions for all {len(y)} flowers ===")
    log(f"Accuracy: {acc_cv:.1%}  ({int((cv_pred == y).sum())} of {len(y)} correct)")
    log(classification_report(y, cv_pred, digits=3))
    cm_cv = confusion_matrix(y, cv_pred, labels=SPECIES)
    wrong = df[cv_pred != y.to_numpy()].assign(predicted=cv_pred[cv_pred != y.to_numpy()])
    if len(wrong):
        log("Flowers the model got wrong in cross-validation:")
        log(wrong.round(1).to_string())
        wrong.to_csv(os.path.join(args.out, "misclassified_flowers.csv"), index=False)

    style()
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.3))
    draw_confusion(axes[0], cm_te, f"Hold-out test ({len(y_te)} flowers): {acc_te:.0%}")
    draw_confusion(axes[1], cm_cv, f"5-fold CV, all {len(y)} flowers: {acc_cv:.0%}")
    axes[0].set_ylabel("True species")
    save(fig, args.out, "confusion_matrix.png")

    plot_boundary(best, df, best_name, args.out)
    imp = plot_importance(df, args.out)
    log("Random Forest feature importance: " + ", ".join(f"{k} {v:.0%}" for k, v in imp.items()))

    # final model on all data
    final = clone(best).fit(X, y)
    path = os.path.join(args.out, "iris_model.joblib")
    joblib.dump({"model": final, "features": FEATURES, "classes": list(final.classes_)}, path)
    log(f"\nFinal {best_name} trained on all {len(df)} flowers and saved to {path}")

    log("\nExample predictions with the final model:")
    samples = [(args.predict if args.predict else None, "your flower"),
               ([5.1, 3.5, 1.4, 0.2], "small petals"), ([6.0, 2.9, 4.5, 1.5], "medium petals"),
               ([6.9, 3.1, 5.4, 2.1], "large petals")]
    for row, label in samples:
        if row is None:
            continue
        pred, conf = describe(final, row)
        log(f"  {row} ({label}) -> {pred}   [{conf}]")

    with open(os.path.join(args.out, "results_summary.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(_LOG))
    log(f"\nSaved outputs to {os.path.abspath(args.out)}")


if __name__ == "__main__":
    main()